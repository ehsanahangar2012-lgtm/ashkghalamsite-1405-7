export const Library: React.FC = () => {
  const [downloadedCode, setDownloadedCode] = useState<string | null>(null);

  const handleDownloadPdf = (std: StandardDoc) => {
    const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
    doc.setFillColor(15, 23, 42);
    doc.rect(0, 0, 210, 36, 'F');
    doc.setTextColor(245, 158, 11);
    doc.setFontSize(18);
    doc.text('ASHK GHALAM PACKAGING ENGINEERING', 18, 17);
    doc.setTextColor(226, 232, 240);
    doc.setFontSize(11);
    doc.text(std.englishSummary, 18, 26);

    doc.setTextColor(30, 41, 59);
    doc.setFontSize(14);
    doc.text(`Standard Code: ${std.code}`, 18, 52);
    doc.setFontSize(11);
    doc.text('Technical Parameters & Production Tolerances:', 18, 66);

    let y = 78;
    std.specs.forEach((line) => {
      doc.text(`- ${line}`, 22, y);
      y += 10;
    });

    doc.setTextColor(100, 116, 139);
    doc.setFontSize(9);
    doc.text('Generated by Ashk Ghalam CAD & Packaging Platform (ashkghalam.ir)', 18, 280);

    doc.save(`${std.code.replace(/\s+/g, '-').toLowerCase()}-spec.pdf`);
    setDownloadedCode(std.code);
    setTimeout(() => setDownloadedCode(null), 2500);
  };

  return (
    <div className="max-w-6xl mx-auto p-4 md:p-8 font-sans dir-rtl text-right">
      <div className="mb-8">
        <div className="flex flex-wrap items-center gap-3 mb-3">
          <BackButton label="بازگشت" fallbackPath="/" variant="auto" />
          <span className="text-xs font-black text-amber-600 dark:text-amber-500 bg-amber-500/10 px-3 py-1 rounded-full border border-amber-500/20">
            کتابخانه فنی و مراجع مهندسی
          </span>
        </div>
        <h1 className="text-3xl font-black text-slate-900 dark:text-slate-100 mt-2">مرجع تخصصی استانداردهای بسته‌بندی و FEFCO</h1>
        <p className="text-slate-600 dark:text-slate-400 text-sm mt-1">
          دسترسی به مستندات فنی، نقشه‌های اجرایی دایکات و راهنماهای کالیبراسیون خطوط تولید کارتن اشک قلم.
        </p>
      </div>

      <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
        {standards.map((std) => {
          const isDone = downloadedCode === std.code;
          return (
            <Card key={std.code} className="flex flex-col justify-between hover:border-amber-500/40 transition-all">
              <div>
                <div className="flex items-center justify-between mb-3">
                  <span className="font-mono text-xs font-bold text-amber-700 dark:text-amber-400 bg-amber-500/10 border border-amber-500/20 px-2.5 py-1 rounded-lg">
                    {std.code}
                  </span>
                  <span className="text-xs text-slate-500 dark:text-slate-400">{std.pages}</span>
                </div>
                <h3 className="text-lg font-bold text-slate-900 dark:text-slate-100 mb-2">{std.title}</h3>
                <p className="text-xs text-slate-600 dark:text-slate-400 leading-relaxed mb-4">{std.description}</p>
              </div>

              <div className="pt-4 border-t border-slate-200 dark:border-slate-800 flex items-center justify-between">
                <span className="text-xs text-emerald-600 dark:text-emerald-400 font-bold flex items-center gap-1">
                  <FileText className="w-3.5 h-3.5" />
                  آماده دانلود
                </span>
                <Button variant="outline" size="sm" onClick={() => handleDownloadPdf(std)}>
                  {isDone ? (
                    <>
                      <Check className="w-3.5 h-3.5 ml-1.5 text-emerald-500" />
                      فایل PDF دریافت شد
                    </>
                  ) : (
                    <>
                      <Download className="w-3.5 h-3.5 ml-1.5" />
                      دریافت PDF راهنما
                    </>
                  )}
                </Button>
              </div>
            </Card>
          );
        })}
      </div>
    </div>
  );
};
