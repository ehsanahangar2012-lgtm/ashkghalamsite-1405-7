import fs from 'fs';
import path from 'path';
import { AGENT_CONFIG } from '../config';
import { AgentBlogPost } from '../types';
import { logger } from '../utils/logger';

interface SitemapUrl {
  loc: string;
  lastmod: string;
  changefreq: 'daily' | 'weekly' | 'monthly';
  priority: string;
}

function escapeXml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

export function buildSitemapAndRobots(allowedBotsOverride?: {
  google?: boolean;
  gpt?: boolean;
  claude?: boolean;
  perplexity?: boolean;
}): { urls: string[]; sitemapXml: string; robotsTxt: string } {
  const baseUrl = AGENT_CONFIG.site.baseUrl;
  const today = new Date().toISOString().slice(0, 10);

  const staticPaths: Array<{ path: string; priority: string; freq: SitemapUrl['changefreq'] }> = [
    { path: '/', priority: '1.0', freq: 'daily' },
    { path: '/catalog', priority: '0.9', freq: 'weekly' },
    { path: '/products', priority: '0.9', freq: 'weekly' },
    { path: '/services', priority: '0.8', freq: 'weekly' },
    { path: '/portfolio', priority: '0.8', freq: 'weekly' },
    { path: '/blog', priority: '0.9', freq: 'daily' },
    { path: '/library', priority: '0.7', freq: 'weekly' },
    { path: '/tools/dieline', priority: '0.8', freq: 'monthly' },
    { path: '/tools/design-studio', priority: '0.8', freq: 'monthly' },
    { path: '/tools/autocad', priority: '0.7', freq: 'monthly' },
    { path: '/software', priority: '0.7', freq: 'monthly' },
    { path: '/inquiry', priority: '0.8', freq: 'monthly' },
    { path: '/about', priority: '0.6', freq: 'monthly' },
  ];

  const entries: SitemapUrl[] = staticPaths.map((s) => ({
    loc: `${baseUrl}${s.path}`,
    lastmod: today,
    changefreq: s.freq,
    priority: s.priority,
  }));

  if (fs.existsSync(AGENT_CONFIG.paths.catalogsFile)) {
    try {
      const catalogs = JSON.parse(fs.readFileSync(AGENT_CONFIG.paths.catalogsFile, 'utf-8')) as any[];
      for (const c of catalogs) {
        if (c && c.isPublished !== false) {
          const slug = c.slug || c.id;
          entries.push({
            loc: `${baseUrl}/catalog/${encodeURIComponent(String(slug))}`,
            lastmod: String(c.updatedAt || today).slice(0, 10),
            changefreq: 'weekly',
            priority: '0.8',
          });
        }
      }
    } catch (err) {
      logger.warn('SitemapBuilder', 'Failed reading catalogs.json', { err });
    }
  }

  if (fs.existsSync(AGENT_CONFIG.paths.postsFile)) {
    try {
      const posts = JSON.parse(fs.readFileSync(AGENT_CONFIG.paths.postsFile, 'utf-8')) as AgentBlogPost[];
      for (const p of posts) {
        if (p && p.status !== 'draft' && p.status !== 'rejected') {
          entries.push({
            loc: `${baseUrl}/blog/${encodeURIComponent(p.slug || p.id)}`,
            lastmod: String(p.updatedAtIso || p.createdAtIso || today).slice(0, 10),
            changefreq: 'weekly',
            priority: '0.8',
          });
        }
      }
    } catch (err) {
      logger.warn('SitemapBuilder', 'Failed reading posts.json', { err });
    }
  }

  const sitemapXml = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${entries
  .map(
    (u) => `  <url>
    <loc>${escapeXml(u.loc)}</loc>
    <lastmod>${u.lastmod}</lastmod>
    <changefreq>${u.changefreq}</changefreq>
    <priority>${u.priority}</priority>
  </url>`
  )
  .join('\n')}
</urlset>
`;

  let settingsBots: Record<string, boolean> = {};
  if (fs.existsSync(AGENT_CONFIG.paths.settingsFile)) {
    try {
      const settings = JSON.parse(fs.readFileSync(AGENT_CONFIG.paths.settingsFile, 'utf-8'));
      settingsBots = settings?.seoRobotsBots || {};
    } catch {}
  }

  const bots = {
    google: allowedBotsOverride?.google ?? settingsBots.google ?? true,
    gpt: allowedBotsOverride?.gpt ?? settingsBots.gpt ?? true,
    claude: allowedBotsOverride?.claude ?? settingsBots.claude ?? true,
    perplexity: allowedBotsOverride?.perplexity ?? settingsBots.perplexity ?? true,
  };

  const robotsTxt = `# Generated by Ashk Ghalam SEO Agent
Sitemap: ${baseUrl}/sitemap.xml

User-agent: *
Allow: /
Disallow: /admin
Disallow: /dashboard
Disallow: /api/agent/

# AI Search & Crawler Controls
User-agent: Google-Extended
${bots.google ? 'Allow: /' : 'Disallow: /'}

User-agent: GPTBot
${bots.gpt ? 'Allow: /' : 'Disallow: /'}

User-agent: ClaudeBot
${bots.claude ? 'Allow: /' : 'Disallow: /'}

User-agent: PerplexityBot
${bots.perplexity ? 'Allow: /' : 'Disallow: /'}
`;

  fs.mkdirSync(path.dirname(AGENT_CONFIG.paths.sitemapFile), { recursive: true });
  fs.writeFileSync(AGENT_CONFIG.paths.sitemapFile, sitemapXml, 'utf-8');
  fs.writeFileSync(AGENT_CONFIG.paths.robotsFile, robotsTxt, 'utf-8');

  logger.info('SitemapBuilder', `Built sitemap.xml (${entries.length} URLs) and robots.txt`);
  return { urls: entries.map((e) => e.loc), sitemapXml, robotsTxt };
}
